fn projectNameFromCwd(allocator: std.mem.Allocator) []const u8 {
    const cwd = core.fs.currentPathAlloc(allocator) catch return "app";
    return projectDisplayNameFromPath(cwd);
}

fn validateNewProjectPath(path: []const u8) ProjectPathValidationError!void {
    if (path.len == 0) return ProjectPathValidationError.EmptyPath;
    if (std.fs.path.isAbsolute(path)) return ProjectPathValidationError.AbsolutePath;

    var component_iter = std.mem.tokenizeAny(u8, path, "/\\");
    var saw_component = false;
    while (component_iter.next()) |component| {
        saw_component = true;
        if (std.mem.eql(u8, component, ".")) return ProjectPathValidationError.CurrentDirectorySegment;
        if (std.mem.eql(u8, component, "..")) return ProjectPathValidationError.TraversalSegment;
    }

    if (!saw_component) return ProjectPathValidationError.EmptyPath;
}

fn projectDisplayNameFromPath(path: []const u8) []const u8 {
    const base = std.fs.path.basename(path);
    if (base.len == 0) return "app";
    if (std.mem.eql(u8, base, ".") or std.mem.eql(u8, base, "..")) return "app";
    for (base) |c| {
        if (c == '/' or c == '\\') return "app";
    }
    return base;
}

fn normalizeTargetBaseId(allocator: std.mem.Allocator, project_name: []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    defer out.deinit(allocator);

    var last_sep = false;
    for (project_name) |c| {
        if (std.ascii.isAlphanumeric(c)) {
            try out.append(allocator, std.ascii.toLower(c));
            last_sep = false;
            continue;
        }

        if (out.items.len > 0 and !last_sep) {
            try out.append(allocator, '_');
            last_sep = true;
        }
    }

    while (out.items.len > 0 and out.items[out.items.len - 1] == '_') {
        _ = out.pop();
    }

    if (out.items.len == 0) {
        try out.appendSlice(allocator, "app");
    }

    if (std.ascii.isDigit(out.items[0])) {
        return try std.fmt.allocPrint(allocator, "app_{s}", .{out.items});
    }

    return try allocator.dupe(u8, out.items);
}
