pub fn handleNew(ctx: *Context, command_args: []const []const u8) !u8 {
    if (command_args.len == 0) {
        try ctx.printErr("error: missing project name\n", .{});
        return 2;
    }
    if (command_args.len != 1) {
        try ctx.printErr("error: new takes exactly one project path argument\n", .{});
        return 2;
    }

    const root_path = command_args[0];
    validateNewProjectPath(root_path) catch |err| {
        switch (err) {
            error.EmptyPath => try ctx.printErr("error: project path cannot be empty\n", .{}),
            error.AbsolutePath => try ctx.printErr("error: project path must be relative\n", .{}),
            error.TraversalSegment => try ctx.printErr("error: project path cannot contain '..' segments\n", .{}),
            error.CurrentDirectorySegment => try ctx.printErr("error: project path cannot contain '.' segments\n", .{}),
        }
        return 2;
    };

    const project_name = projectDisplayNameFromPath(root_path);
    const target_base_id = try normalizeTargetBaseId(ctx.allocator, project_name);
    try scaffold.createProjectSkeleton(ctx.allocator, root_path, project_name, target_base_id);
    try core.fs.writeFile(
        try std.fmt.allocPrint(ctx.allocator, "{s}/README.md", .{root_path}),
        "Generated by OVO\n",
    );
    try ctx.print("new: created project '{s}'\n", .{root_path});
    return 0;
}

